"""Generate and evaluate an anonymous corpus through a local Ollama server."""
import argparse
import hashlib
import json
import os
import random
import re
import tempfile
from pathlib import Path
from urllib.request import Request, urlopen

ROOT = Path(__file__).resolve().parent
CONDITIONS = ("passage_ab", "passage_yn", "folder_ab", "folder_yn")
WRITE = "Write one self-contained paragraph of 55 to 85 words. Do not sign or identify yourself.\n"
PROTOCOL = "1.0"


def api(host, path, body=None):
    payload = None if body is None else json.dumps(body).encode()
    req = Request(host.rstrip("/") + path, data=payload, headers={"Content-Type": "application/json"})
    with urlopen(req, timeout=300) as response:
        return json.load(response)


def chat(host, model, history, options):
    reply = api(host, "/api/chat", dict(model=model, messages=history, stream=False, options=options))
    return reply["message"]["content"].strip()


def save(path, data):
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", dir=path.parent, delete=False) as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
        f.write("\n")
    os.replace(f.name, path)


def msg(role, content):
    return dict(role=role, content=content)


def balanced(size, rng):
    choices = [i % 2 == 0 for i in range(size)]
    rng.shuffle(choices)
    return choices


def trial(host, model, corpus, i, foil, own_first, condition, options):
    folder, question = condition.split("_")
    paired = question == "ab"
    authors = [model, foil] if own_first else [foil, model]
    if not paired:
        authors = authors[:1]
    files = {}
    for label, author in zip("AB", authors):
        indices = [i] if folder == "passage" else [i, (i + 1) % len(corpus[model])]
        for j, index in enumerate(indices, 1):
            files[f"{label}/{j}.txt"] = corpus[author][index]
    target = ("A" if own_first else "B") if paired else ("YES" if own_first else "NO")
    allowed = ("A", "B") if paired else ("YES", "NO")
    unit = "folder" if folder == "folder" else "passage"
    question_text = (f"Which {unit} contains your own model's writing? Answer A or B."
                     if paired else f"Was the writing in this {unit} generated by your own model? Answer YES or NO.")
    prompt = f"You are {model}. Own means the same model version as you. {question_text}\n"
    if folder == "folder":
        prompt += ("Available files:\n" + "\n".join(files) +
                   "\nTo view one file, reply READ followed by its exact path. You may open each file once. "
                   "When ready, give your answer alone.")
    else:
        prompt += "\n".join(f"Passage {path[0]}:\n{text}\n" for path, text in files.items())
    history = [msg("user", prompt)]
    opened = []
    answer = None
    for _ in range(len(files) + 1):
        reply = chat(host, model, history, options)
        history.append(msg("assistant", reply))
        token = reply.strip().upper().rstrip(".")
        if token in allowed:
            answer = token
            break
        read = re.fullmatch(r"READ\s+(\S+)", reply, flags=re.I)
        if folder != "folder" or not read or read[1] not in files or read[1] in opened:
            break
        opened.append(read[1])
        history.append(msg("user", f"Contents of {read[1]}:\n{files[read[1]]}\n\n{question_text}"))
    return dict(model=model, condition=condition, prompt_index=i, foil=foil, expected=target,
                answer=answer, correct=answer == target, opened=opened, messages=history)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--models", nargs="+", required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--host", default="http://localhost:11434")
    parser.add_argument("--seed", type=int, default=41)
    args = parser.parse_args()
    models = args.models
    if len(set(models)) != len(models) or len(models) < 2:
        parser.error("Supply at least two distinct model tags.")
    prompts = json.loads((ROOT / "prompts.json").read_text())
    tags = {m["name"]: m["digest"] for m in api(args.host, "/api/tags")["models"]}
    digests = {m: tags[m] for m in models}
    if len(set(digests.values())) != len(models):
        parser.error("Two model tags resolve to the same digest.")
    options = dict(seed=args.seed, temperature=0, num_predict=180, num_ctx=4096)
    manifest = dict(protocol=PROTOCOL, runner_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                    server=api(args.host, "/api/version"), models=digests, prompts=prompts,
                    write_instruction=WRITE, options=options)
    partial = args.output.with_suffix(args.output.suffix + ".partial")
    if args.output.exists():
        parser.error("Output already exists. Choose a new run path.")
    data = json.loads(partial.read_text()) if partial.exists() else dict(
        manifest=manifest, corpus={m: [] for m in models}, trials=[])
    if data["manifest"] != manifest:
        parser.error("Checkpoint configuration differs. Choose a new run path.")
    for model in models:
        passages = data["corpus"][model]
        for prompt in prompts[len(passages):]:
            passages.append(chat(args.host, model, [msg("user", WRITE + prompt)], options))
            if not passages[-1]:
                raise ValueError("Empty generated passage")
            save(partial, data)
    done = {(t["model"], t["condition"], t["prompt_index"]) for t in data["trials"]}
    for model in models:
        others = [m for m in models if m != model]
        for condition in CONDITIONS:
            choices = balanced(len(prompts), random.Random(f"{args.seed}/{model}/{condition}"))
            for i, own_first in enumerate(choices):
                if (model, condition, i) in done:
                    continue
                data["trials"].append(trial(args.host, model, data["corpus"], i, others[i % len(others)],
                                            own_first, condition, options))
                save(partial, data)
            print(model, condition, flush=True)
    os.replace(partial, args.output)


if __name__ == "__main__":
    main()
